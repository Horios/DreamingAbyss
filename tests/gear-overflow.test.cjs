'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),path=require('node:path');
const {loadRuntime}=require('./headless-runtime.cjs');
const root=path.resolve(__dirname,'..');
const inspect=(r,expression)=>JSON.parse(r.run('JSON.stringify('+expression+')'));
test('full shared backpack salvages only the incoming gear, preserving owned items and ongoing combat',()=>{
 const r=loadRuntime(root);
 r.run('selectSaveSlot(1);start(0);closeModal();startSelectedExploration()');
 assert.equal(r.run('running'),true);
 const before=inspect(r,'({gear:state.bag.map(g=>g.id),ore:state.ore,dust:state.dust})');
 const capacity=before.gear.length+1;
 r.run('GAMEPLAY_SETTINGS.equipment.bagCapacity='+capacity+';globalThis.__EMBERWILD_GAMEPLAY_SETTINGS.equipment.bagCapacity='+capacity);
 assert.equal(r.run('RULES.bagCapacity'),capacity);
 r.run('addGear(gear(1,0,0,state.job))');
 const full=inspect(r,'({gear:state.bag.map(g=>g.id),ore:state.ore,dust:state.dust})');
 assert.equal(full.gear.length,capacity,'one available slot accepts exactly one item');
 assert(full.gear.every(id=>typeof id==='string'));
 assert(before.gear.every(id=>full.gear.includes(id)),'existing gear is preserved');
 r.run('addGear(gear(1,0,0,state.job))');
 const after=inspect(r,'({gear:state.bag.map(g=>g.id),ore:state.ore,dust:state.dust,running})');
 assert.deepEqual(after.gear,full.gear,'overflow neither appends nor replaces an owned item');
 assert.equal(after.ore,full.ore+3,'tier-one unmodified overflow yields forge material');
 assert.equal(after.dust,full.dust+1,'tier-one unmodified overflow yields dust');
 assert.equal(after.running,true,'full bag does not terminate exploration');
 assert.equal(r.run('save()'),true);
 const saved=JSON.parse(r.values.get(r.run('KEY')));
 assert.deepEqual(saved.members[0].bag.map(g=>g.id),full.gear);
 assert.equal(saved.members[0].ore,after.ore);
 assert.equal(saved.members[0].dust,after.dust);
});
